// npm run unity:sim — builds the Unity preview's simulator bundle and writes it with a header
// (source hash) to unity/Jcreatepp/Editor/Preview/Sim/jcreatepp-sim.txt.
// The extension is .txt on purpose: a .js file would be imported by Cluster Creator Kit as an item script.
const fs = require('fs');
const path = require('path');
const webpack = require('webpack');
const config = require('../webpack.unity.config.js');
const { inputFiles, inputsHash } = require('./unitySimInputs');

const root = path.resolve(__dirname, '..');
const outFile = path.join(root, 'unity/Jcreatepp/Editor/Preview/Sim/jcreatepp-sim.txt');

webpack(config, (err, stats) => {
  if (err || stats.hasErrors()) {
    console.error(err || stats.toString({ colors: false, all: false, errors: true }));
    process.exit(1);
  }
  const bundle = fs.readFileSync(path.join(config.output.path, config.output.filename), 'utf8').replace(/\r\n/g, '\n');
  const header = [
    '// Jcreate++ simulator for the Unity editor preview. Generated by `npm run unity:sim`; do not edit.',
    `// source-hash: ${inputsHash(root)}`,
    `// sources: ${inputFiles(root).join(', ')}`,
    '',
  ].join('\n');
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, header + bundle);
  fs.rmSync(config.output.path, { recursive: true, force: true });
  console.log(`wrote ${path.relative(root, outFile)} (${(header + bundle).length} chars)`);
});
