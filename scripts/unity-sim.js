// npm run unity:sim — builds the Unity extension's bundles and writes each with a header (source hash):
// - unity/Jcreatepp/Editor/Preview/Sim/jcreatepp-sim.txt (the preview's simulator)
// - unity/Jcreatepp/Editor/Core/jcreatepp-core.txt (headless Blockly + converter + codegen + parts)
// The extension is .txt on purpose: a .js file would be imported by Cluster Creator Kit as an item script.
const fs = require('fs');
const path = require('path');
const webpack = require('webpack');
const configs = require('../webpack.unity.config.js');
const { inputFiles, inputsHash } = require('./unitySimInputs');

const root = path.resolve(__dirname, '..');
const OUT = {
  sim: {
    file: 'unity/Jcreatepp/Editor/Preview/Sim/jcreatepp-sim.txt',
    title: 'Jcreate++ simulator for the Unity editor preview.',
  },
  core: {
    file: 'unity/Jcreatepp/Editor/Core/jcreatepp-core.txt',
    title: 'Jcreate++ block core for the Unity editor. Includes Blockly (Copyright Google LLC, Apache-2.0; see THIRD-PARTY-NOTICES.md next to this file).',
  },
};

webpack(configs, (err, stats) => {
  if (err || stats.hasErrors()) {
    console.error(err || stats.toString({ colors: false, all: false, errors: true }));
    process.exit(1);
  }
  for (const config of configs) {
    const out = OUT[config.name];
    const bundle = fs.readFileSync(path.join(config.output.path, config.output.filename), 'utf8').replace(/\r\n/g, '\n');
    const header = [
      `// ${out.title} Generated by \`npm run unity:sim\`; do not edit.`,
      `// source-hash: ${inputsHash(root, config.name)}`,
      `// sources: ${inputFiles(root, config.name).join(', ')}`,
      '',
    ].join('\n');
    const outFile = path.join(root, out.file);
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, header + bundle);
    console.log(`wrote ${out.file} (${(header + bundle).length} chars)`);
  }
  fs.rmSync(path.join(root, '.unity-sim-build'), { recursive: true, force: true });
});
